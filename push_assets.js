// Pushes converted models (build/playtest_assets, made by tools/converter/convert.js) into the open
// Studio place over StudioMCP:
//   ReplicatedStorage.MBE_PlaytestAssets.<Id>  ModuleScript returning the mesh/texture data. Studio caps
//                                              a script at 200,000 characters, so each base64 blob is
//                                              split into child ModuleScripts (<Blob>_1, _2, ...)
//                                              that the parent joins back together.
//   ServerStorage.MBE_Models.<Id>              Model with one invisible "ImportAnchor" part sized to the
//                                              model, tagged MBE_ImportedMesh. The server's existing
//                                              CreatureVisuals.AttachCustomModel clones/scales/welds it;
//                                              ImportedMeshes.client builds the visible mesh on each client.
// Hand-made models already in MBE_Models (no MBE_Imported attribute) are never replaced.
// Usage: node tools/push_assets.js [Id ...]      push (no ids = everything in the manifest)
//        node tools/push_assets.js --remove      delete all imported templates + data (back to placeholders)
const fs = require('fs');
const path = require('path');
const os = require('os');
const { execFileSync } = require('child_process');

const root = path.resolve(__dirname, '..');
const dir = path.join(root, 'build', 'playtest_assets');
const args = process.argv.slice(2);

function run(code) {
  const tmp = path.join(os.tmpdir(), 'mbe_push_assets.lua');
  fs.writeFileSync(tmp, code);
  return execFileSync('node', [path.join(__dirname, 'mcp_call.js'), 'luau', tmp, 'Edit'],
    { encoding: 'utf8', timeout: 115000, maxBuffer: 64 << 20 }).trim();
}
function longString(s) {
  let eq = '';
  while (s.includes(']' + eq + ']')) eq += '=';
  return '[' + eq + '[\n' + s + ']' + eq + ']';
}

if (args[0] === '--remove') {
  console.log(run(`
local n = 0
local models = game:GetService("ServerStorage"):FindFirstChild("MBE_Models")
if models then for _, m in models:GetChildren() do if m:GetAttribute("MBE_Imported") then m:Destroy() n += 1 end end end
local data = game:GetService("ReplicatedStorage"):FindFirstChild("MBE_PlaytestAssets")
if data then data:Destroy() end
return "removed " .. n .. " imported templates and the data folder"`));
  process.exit(0);
}

const manifest = JSON.parse(fs.readFileSync(path.join(dir, 'manifest.json'), 'utf8'));
const ids = args.length ? args : Object.keys(manifest);
const CHUNK = 190000;
for (const id of ids) {
  const m = manifest[id];
  if (!m) { console.log(`skip ${id}: not in manifest (run tools/converter/convert.js first)`); continue; }
  const data = JSON.parse(fs.readFileSync(path.join(dir, id + '.json'), 'utf8'));
  const chunks = []; // [blobName, index, text]
  const counts = {};
  const blob = (name, text) => {
    counts[name] = Math.ceil(text.length / CHUNK);
    for (let i = 0; i < counts[name]; i++) chunks.push([name, i + 1, text.slice(i * CHUNK, (i + 1) * CHUNK)]);
    return `blob(${JSON.stringify(name)})`;
  };
  const v3 = a => `Vector3.new(${a.join(', ')})`;
  let main = `-- Generated by tools/push_assets.js from build/playtest_assets/${id}.json. Private playtest data: do not publish.
local function blob(name: string): string
	local parts = {}
	for i = 1, script:GetAttribute(name) do
		parts[i] = require(script:WaitForChild(name .. "_" .. i))
	end
	return table.concat(parts)
end
return {
	Version = ${data.Version}, Name = ${JSON.stringify(data.Name)}, Source = ${JSON.stringify(data.Source)},
	Size = ${v3(data.Size)},
	Submeshes = {
`;
  data.Submeshes.forEach((sub, i) => {
    const p = 'S' + (i + 1) + '_';
    main += `		{
			Name = ${JSON.stringify(sub.Name)}, VertexCount = ${sub.VertexCount}, TriangleCount = ${sub.TriangleCount},
			Positions = ${blob(p + 'Positions', sub.Positions)}, Normals = ${blob(p + 'Normals', sub.Normals)},
			UVs = ${blob(p + 'UVs', sub.UVs)}, Indices = ${blob(p + 'Indices', sub.Indices)},
			Color = Color3.new(${sub.Color.map(c => c.toFixed(3)).join(', ')}),
`;
    if (sub.Texture) main += `			Texture = { Width = ${sub.Texture.Width}, Height = ${sub.Texture.Height}, Pixels = ${blob(p + 'Pixels', sub.Texture.Pixels)} },
`;
    main += `		},
`;
  });
  main += `	},
}
`;
  const [sx, sy, sz] = m.size;
  const attrs = (m.height ? `model:SetAttribute("Height", ${m.height}) ` : '') + (m.yaw ? `model:SetAttribute("YawOffset", ${m.yaw}) ` : '');
  let makeChunks = '';
  for (const [name, i, text] of chunks)
    makeChunks += `do local c = Instance.new("ModuleScript") c.Name = "${name}_${i}" c.Source = 'return "${text}"' c.Parent = mod end
`;
  for (const [name, n] of Object.entries(counts)) makeChunks += `mod:SetAttribute("${name}", ${n})
`;
  console.log(run(`
local RS, SS = game:GetService("ReplicatedStorage"), game:GetService("ServerStorage")
local id = ${JSON.stringify(id)}
local folder = RS:FindFirstChild("MBE_PlaytestAssets") or Instance.new("Folder")
folder.Name = "MBE_PlaytestAssets" folder.Parent = RS
local old = folder:FindFirstChild(id) if old then old:Destroy() end
local mod = Instance.new("ModuleScript") mod.Name = id
mod.Source = ${longString(main)}
${makeChunks}mod.Parent = folder
local models = SS:FindFirstChild("MBE_Models") or Instance.new("Folder")
models.Name = "MBE_Models" models.Parent = SS
local existing = models:FindFirstChild(id)
if existing and not existing:GetAttribute("MBE_Imported") then
  return "data pushed for " .. id .. ", but kept your own model in MBE_Models." .. id
end
if existing then existing:Destroy() end
local model = Instance.new("Model") model.Name = id
model:SetAttribute("MBE_Imported", true) ${attrs}
local anchor = Instance.new("Part") anchor.Name = "ImportAnchor"
anchor.Size = Vector3.new(${sx}, ${sy}, ${sz}) anchor.CFrame = CFrame.new(0, ${sy / 2}, 0)
anchor.Transparency = 1 anchor.Anchored = true anchor.CanCollide = false anchor.CanTouch = false anchor.CanQuery = false
anchor:SetAttribute("MBE_ImportedMesh", id) anchor:AddTag("MBE_ImportedMesh")
anchor.Parent = model model.PrimaryPart = anchor model.Parent = models
return "pushed " .. id .. " (" .. #mod:GetChildren() .. " data chunks)"`));
}
